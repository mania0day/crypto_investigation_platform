# The api_keys table belongs to the schema migration (schema contract). Created
# here when that migration has not reached the test database yet, so the auth
# tests do not depend on which change lands first; a no-op once it has.
API_KEYS_DDL = """
CREATE TABLE IF NOT EXISTS api_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key_id TEXT NOT NULL UNIQUE,
    key_hash TEXT NOT NULL,
    scopes TEXT NOT NULL,
    label TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    revoked_at TIMESTAMPTZ
)
"""


@pytest.fixture
async def keys(engine: AsyncEngine) -> AsyncIterator[async_sessionmaker[AsyncSession]]:
    async with engine.begin() as conn:
        await conn.execute(text(API_KEYS_DDL))
        await conn.execute(text("DELETE FROM api_keys"))
    yield create_session_factory(engine)


def build_app(auth: ApiKeyAuth) -> FastAPI:
    """Two routes, two scopes — the shape the real API will use.

    Each route is wired a different way on purpose, because both wirings must
    enforce: ``/read`` takes the caller as a parameter (so a test can prove
    *which* key was resolved, not merely that something got through), while
    ``/investigate`` guards at the decorator and never sees the key.

    Neither uses ``Annotated[..., Depends(auth.requires(...))]``. Under
    ``from __future__ import annotations`` that annotation is a string
    evaluated against module globals, where the local ``auth`` does not exist;
    FastAPI then reads the parameter as a query parameter and the route stops
    being guarded at all. See ApiKeyAuth's docstring.
    """
    app = FastAPI()
    # Bound to a name first: a bare ``Depends(...)`` call in a default argument
    # is what ruff's B008 objects to, and the name reads the same to FastAPI.
    reader = Depends(auth.requires(Scope.READ))

    @app.get("/read")
    async def read(key: AuthenticatedKey = reader) -> dict[str, object]:
        return {"key_id": key.key_id, "scopes": sorted(key.scopes), "label": key.label}

    @app.post("/investigate", dependencies=[Depends(auth.requires(Scope.INVESTIGATE))])
    async def investigate() -> dict[str, object]:
        return {"started": True}

    return app


async def client_for(auth: ApiKeyAuth) -> httpx.AsyncClient:
    transport = httpx.ASGITransport(app=build_app(auth))
    return httpx.AsyncClient(transport=transport, base_url="http://test")


@pytest.fixture
async def client(keys: async_sessionmaker[AsyncSession]) -> AsyncIterator[httpx.AsyncClient]:
    async with await client_for(ApiKeyAuth(keys, enabled=True)) as c:
        yield c


async def mint(
    keys: async_sessionmaker[AsyncSession],
    *scopes: Scope,
    label: str | None = None,
) -> MintedKey:
    async with keys() as session:
        return await mint_key(session, scopes, label=label)


def bearer(token: str) -> dict[str, str]:
    return {"Authorization": f"Bearer {token}"}


# ──────────────────────────────── the happy path ────────────────────────────────


async def test_a_valid_key_reaches_the_route_its_scope_covers(
    client: httpx.AsyncClient, keys: async_sessionmaker[AsyncSession]
) -> None:
    """A minted key authenticates, and the route learns who it is talking to."""
    minted = await mint(keys, Scope.READ, Scope.INVESTIGATE, label="Det. Ruiz")

    response = await client.get("/read", headers=bearer(minted.token))

    assert response.status_code == 200, response.text
    body = response.json()
    assert body["key_id"] == minted.key_id
    assert body["scopes"] == ["investigate", "read"]
    assert body["label"] == "Det. Ruiz"


async def test_two_minted_keys_never_share_an_id_or_a_secret(
    keys: async_sessionmaker[AsyncSession],
) -> None:
    """Both halves are drawn from ``secrets``; a collision in either would let
    one investigator's key answer for another's."""
    first = await mint(keys, Scope.READ)
    second = await mint(keys, Scope.READ)

    assert first.key_id != second.key_id
    assert first.secret != second.secret
    assert first.key_id.startswith("cc_")
    assert first.token == f"{first.key_id}.{first.secret}"


