"""The auth layer: the only barrier once the API leaves 127.0.0.1.

These drive the exported dependency exactly as a route will use it, on a
throwaway app declared here rather than through ``create_app``. The real routes
are guarded too, and ``test_route_auth.py`` locks that down; keeping the
dependency's own behaviour on a two-route app means a failure here says "the
guard is broken" instead of "something in the API changed".

Every test here is a regression lock on something that fails silently: a
rejection body that says too much, a revoked key that keeps working, a secret
that turns out to be recoverable from the row that stored it, a second
implementation of the key table drifting away from the first.
"""

